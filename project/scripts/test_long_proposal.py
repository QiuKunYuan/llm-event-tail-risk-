"""Illustrated report regressions; synthetic templates contain no private thesis."""
import hashlib
import json
from pathlib import Path
import re
from types import SimpleNamespace
import sys
import tempfile
import unittest
from unittest.mock import patch
from zipfile import ZipFile

sys.path.insert(0, str(Path(__file__).resolve().parents[2] / 'scripts'))
import build_long_proposal as report

TYPESETTING = ('REPORT_BODY_FONT_SIZE_PT=12.045\nREPORT_BODY_BASELINE_PT=22.08249pt\n') * 8


class LongProposalTests(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.root = Path(self.tmp.name)

    def tearDown(self):
        self.tmp.cleanup()

    def template(self):
        archive = self.root / 'synthetic-template.zip'
        data = b'% Generated by docstrip. LaTeX Project Public License. 3.7.4\n'
        with ZipFile(archive, 'x') as package:
            package.writestr('template/bithesis.cls', data)
            package.writestr('template/chapters/old-thesis.tex', 'Synthetic excluded old text')
            package.writestr('template/originality.pdf', b'Synthetic excluded signature')
            package.writestr('template/font.ttf', b'Synthetic excluded font')
        return archive, data, hashlib.sha256(archive.read_bytes()).hexdigest()

    def test_original_chapters_images_and_signatures_not_imported(self):
        archive, data, sha = self.template()
        with patch.object(report, 'CLASS_HASH', sha):
            report.prepare(archive, self.root / 'build')
        self.assertEqual((self.root / 'build/bithesis.cls').read_bytes(), data)
        self.assertFalse((self.root / 'build/chapters').exists())
        self.assertFalse(list((self.root / 'build').rglob('*.pdf')))
        self.assertFalse(list((self.root / 'build').rglob('*.ttf')))

    def test_template_fingerprint_is_mandatory_before_build(self):
        archive, _, _ = self.template()
        with self.assertRaisesRegex(ValueError, 'differs from the received original'):
            report.prepare(archive, self.root / 'build')
        self.assertFalse((self.root / 'build').exists())

    def test_aggregate_year_counts_and_missing_table_share_one_denominator(self):
        (self.root / 'data').mkdir()
        facts = report.data_tables(self.root)
        self.assertEqual(sum(facts['publication_year_rows'].values()), 3607689)
        lines = (self.root / 'data/missing.dat').read_text().splitlines()
        self.assertEqual(len(lines), 5)
        self.assertAlmostEqual(float(lines[3].split()[0]), 100 * 1732902 / 3607689, places=6)

    def test_bibliography_keeps_all_thirty_four_items_and_safe_urls(self):
        report.bibliography(self.root)
        text = (self.root / 'references.bbl').read_text()
        self.assertEqual(text.count(r'\bibitem{r'), 34)
        self.assertIn(r'\url{https://arxiv.org/abs/2505.09388}', text)
        self.assertEqual(report.escape('x_1 & 10%'), r'x\_1 \& 10\%')

    def test_thirty_pages_is_a_real_compilation_requirement(self):
        (self.root / 'main.log').write_text('Clean synthetic compilation log')
        mocked = SimpleNamespace(returncode=0, stdout='REPORT_BODY_PAGES=29\n', stderr='')
        with patch.object(report.shutil, 'which', return_value='/synthetic/xelatex'), \
             patch.object(report.subprocess, 'run', return_value=mocked):
            with self.assertRaisesRegex(RuntimeError, '29 body pages'):
                report.compile_report(self.root)
        mocked.stdout = 'REPORT_BODY_PAGES=30\n' + TYPESETTING
        with patch.object(report.shutil, 'which', return_value='/synthetic/xelatex'), \
             patch.object(report.subprocess, 'run', return_value=mocked) as run:
            pages, _ = report.compile_report(self.root)
        self.assertEqual(pages, 30)
        self.assertEqual(run.call_count, 3)
        self.assertIn('-no-shell-escape', run.call_args.args[0])
        self.assertNotIn('-shell-escape', run.call_args.args[0])

    def test_missing_engine_is_blocked_not_accepted(self):
        with patch.object(report.shutil, 'which', return_value=None):
            with self.assertRaisesRegex(RuntimeError, 'compilation is not complete'):
                report.compile_report(self.root)

    def test_overfull_references_and_missing_glyphs_are_blocked(self):
        mocked = SimpleNamespace(returncode=0, stdout='REPORT_BODY_PAGES=30\n' + TYPESETTING, stderr='')
        for log, message in [('Overfull \\hbox (1.2pt too wide)', 'Overfull'),
                             ('Overfull \\vbox (2.0pt too high)', 'Overfull'),
                             ('LaTeX Warning: There were undefined references.', 'Unresolved'),
                             ('Missing character: synthetic glyph', 'Missing font glyph')]:
            with self.subTest(log=log):
                (self.root / 'main.log').write_text(log)
                with patch.object(report.shutil, 'which', return_value='/synthetic/xelatex'), \
                     patch.object(report.subprocess, 'run', return_value=mocked):
                    with self.assertRaisesRegex(RuntimeError, message):
                        report.compile_report(self.root)

    def test_template_multiplier_cannot_inflate_body_page_acceptance(self):
        (self.root / 'main.log').write_text('Synthetic clean log')
        mocked = SimpleNamespace(returncode=0, stdout='REPORT_BODY_PAGES=67\n' +
                                 TYPESETTING.replace('22.08249pt', '33.7862pt'), stderr='')
        with patch.object(report.shutil, 'which', return_value='/synthetic/xelatex'), \
             patch.object(report.subprocess, 'run', return_value=mocked):
            with self.assertRaisesRegex(RuntimeError, 'extra template line multiplier'):
                report.compile_report(self.root)

    def test_build_inside_git_repository_is_rejected(self):
        with self.assertRaisesRegex(ValueError, 'outside the Git repository'):
            report.private_directory(report.ROOT / 'generated-fixture')

    def test_bundle_exact_allowlist_ignores_unreviewed_build_assets(self):
        archive, data, sha = self.template()
        directory = self.root / 'build'
        with patch.object(report, 'CLASS_HASH', sha):
            report.prepare(archive, directory)
            (directory / 'raw-rows.json').write_text('{"synthetic_excluded": true}')
            (directory / 'old-thesis.tex').write_text('Synthetic excluded chapter')
            (directory / 'signature.pdf').write_bytes(b'Synthetic excluded signature')
            (directory / 'font.ttf').write_bytes(b'Synthetic excluded font')
            target = self.root / 'source.zip'
            report.source_bundle(directory, target, archive)
        with ZipFile(target) as package:
            self.assertEqual(set(package.namelist()), set(report.BUNDLE_INPUTS))
            self.assertEqual(package.read('bithesis.cls'), data)
            self.assertNotIn('raw-rows.json', package.namelist())
            self.assertNotIn('old-thesis.tex', package.namelist())
            self.assertNotIn('signature.pdf', package.namelist())
            self.assertNotIn('font.ttf', package.namelist())

    def test_modified_class_is_rejected_for_source_bundle(self):
        archive, _, sha = self.template()
        directory = self.root / 'build'
        with patch.object(report, 'CLASS_HASH', sha):
            report.prepare(archive, directory)
            (directory / 'bithesis.cls').write_text('% Synthetic changed class')
            with self.assertRaisesRegex(ValueError, 'class is modified'):
                report.source_bundle(directory, self.root / 'bad.zip', archive)
        self.assertFalse((self.root / 'bad.zip').exists())

    def test_modified_aggregate_cannot_enter_source_bundle(self):
        archive, _, sha = self.template()
        directory = self.root / 'build'
        with patch.object(report, 'CLASS_HASH', sha):
            report.prepare(archive, directory)
            with (directory / 'data/yearly.dat').open('a') as stream:
                stream.write('Synthetic nonaggregate row must be excluded\n')
            with self.assertRaisesRegex(ValueError, 'aggregate input differs'):
                report.source_bundle(directory, self.root / 'bad.zip', archive)
        self.assertFalse((self.root / 'bad.zip').exists())

    def test_symlinked_build_directory_is_rejected(self):
        (self.root / 'real').mkdir()
        (self.root / 'linked').symlink_to(self.root / 'real', target_is_directory=True)
        with self.assertRaisesRegex(ValueError, 'symlink'):
            report.private_directory(self.root / 'linked')

    def test_publishing_requires_explicit_render_inspection(self):
        argv = ['build_long_proposal.py', '--template-zip', str(self.root / 'unused.zip'),
                '--build-dir', str(self.root / 'build'), '--publish']
        with patch.object(sys, 'argv', argv):
            with self.assertRaisesRegex(ValueError, 'inspection of rendered current sources'):
                report.main()
        self.assertFalse((self.root / 'build').exists())

    def test_review_body_length_and_all_real_bibliography_entries(self):
        review = (report.SOURCE.parent / '文献综述-邱琨原.md').read_text(encoding='utf-8')
        body, refs = review.split('## 参考文献', 1)
        body = body[body.index('## 一、'):]
        self.assertGreaterEqual(len(re.findall(r'[\u3400-\u9fff]', body)), 3000)
        self.assertEqual(len(re.findall(r'^\[\d+\]', refs, re.M)), 34)
        self.assertIn('不扣市场、行业或因子', body)
        self.assertNotIn('logit修正上界', body)

    def test_historical_facts_are_not_new_candidate_counts(self):
        facts = json.loads((report.SOURCE / 'data/audit-summary.json').read_text())
        self.assertEqual(facts['daily_returns_rows'], 9091641)
        self.assertEqual(facts['daily_return_missing'], 443905)
        self.assertEqual(facts['label_rows'], 6116554)
        self.assertEqual(facts['label_p10_positive'], 669391)
        self.assertEqual(facts['label_p05_positive'], 358973)
        self.assertEqual(facts['industry_daily_rows'], 50067)
        self.assertEqual(facts['industry_history_rows'], 4393)
        self.assertIsNone(facts['actual_loss_candidate_counts'])
        self.assertFalse(facts['actual_loss_certification_completed'])
        self.assertFalse(facts['listed_universe_certification_completed'])
        self.assertFalse(facts['formal_features_assembled'])
        self.assertIn('retired FF3', facts['historical_label_semantics'])
        subset = facts['market_candidate_subset_audit']
        self.assertEqual(subset['requested_historical_dates'], 61)
        self.assertEqual(subset['conflicting_dates'], 61)
        self.assertEqual(subset['conflicting_security_rows'], 111758)
        self.assertFalse(subset['market_series_identity_certified'])
        self.assertIn('not all 2329', subset['scope'])
        recovery = facts['history_fields_recovery_audit']
        self.assertEqual(recovery['old_industry_columns_literal_equal_rows'], 4393)
        self.assertEqual(recovery['old_status_columns_literal_equal_rows'], 2971)
        self.assertEqual(recovery['recovered_status_isin_missing'], 8)
        self.assertFalse(recovery['historical_intervals_certified'])

    def test_master_cover_and_actual_loss_source_contract(self):
        main = (report.SOURCE / 'main.tex').read_text()
        self.assertIn('type=master', main)
        self.assertIn('专业学位硕士', main)
        self.assertIn('基于多维时序数据融合的短期证券市场风险预测', main)
        self.assertNotIn('有界残差融合', main)
        data = (report.SOURCE / 'methods/data_events.tex').read_text()
        self.assertIn(r'\prod_{k=1}^{5}(1+r_{i,t+k})-1', data)
        self.assertIn(r'R_{i,t}^{(5)}\le-0.10', data)
        self.assertIn('左连接', data)
        experiments = (report.SOURCE / 'methods/experiments_system.tex').read_text()
        self.assertIn('$V_{tune}$', experiments)
        self.assertIn('$V_{cal}$', experiments)
        self.assertIn('重叠的移动日期块', experiments)
        self.assertIn('42、2024、7、123、3407', experiments)
        figures = (report.SOURCE / 'figures/figures.tex').read_text()
        self.assertEqual(len(re.findall(r'\\newcommand\{\\Fig', figures)), 22)


if __name__ == '__main__':
    unittest.main()
